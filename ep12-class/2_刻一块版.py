# 第二版：class 鲤鱼 = 刻一块版；鲤鱼("小红", "红") = 拿红墨印一张。
# print(小红) 打出来是一串地址：整张鱼打印不出来，只告诉你它放在内存哪儿。
class 鲤鱼:
    def __init__(self, 名字, 颜色):
        self.名字 = 名字          # 这一张自己的名字
        self.颜色 = 颜色          # 这一张自己的颜色

    def 游(self):
        print(self.名字, "游走了")

小红 = 鲤鱼("小红", "红")
小金 = 鲤鱼("小金", "金")
print(小红)
