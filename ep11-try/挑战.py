# 编程挑战：看不懂的 5 行里，有 4 行人一眼就能看懂：
#   奶茶 十五 · 外卖 23元 · 地铁 3.5 · 煎饼 加蛋 8
# 改这个程序，把这 4 行也算进去（空行照样跳过）。做对了，总数是 15947.5。
# 改完运行 python 检查挑战.py 看看对不对。
总数 = 0
坏行 = 0
for 行 in open("账单.txt", encoding="utf-8"):
    try:
        钱 = 行.split()[1]
        总数 += int(钱)
    except (ValueError, IndexError):
        坏行 += 1
print("今年花了", 总数, "元，看不懂的有", 坏行, "行")
