"""
编程挑战的测试器：戴眼镜的 AI（规则三），用 5 组随机种子各训练一遍、各测 200 局，
每一组的平均苹果数都要 ≥ 28 个才算过关。

    python challenge_test.py

改 snake_ai.py 里的东西来提高成绩（怎么改，自己想）。
跑一次要几分钟，耐心等。只换随机种子来"碰运气"是没用的：5 组都要过。
"""
import snake_ai

过关线 = 28
测试种子 = [12, 13, 14, 15, 16]

if __name__ == "__main__":
    全过 = True
    for 种子 in 测试种子:
        账本, _ = snake_ai.训练(3, 种子)
        成绩 = snake_ai.测试(账本, 3)
        平均 = sum(c[1] for c in 成绩) / len(成绩)
        过了 = 平均 >= 过关线
        全过 = 全过 and 过了
        print(f"种子 {种子}：平均吃 {平均:.2f} 个  {'✓' if 过了 else '✗'}", flush=True)
    print("\n挑战成功！把你改了什么、成绩截图发到评论区吧" if 全过 else f"\n还差一点。5 组都要 ≥ {过关线} 个才算过关")
