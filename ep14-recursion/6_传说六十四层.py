import time

def 搬(n, 从, 到, 借):            # 这次不打印，只数一共搬了几次
    if n == 1:
        return 1
    return 搬(n - 1, 从, 借, 到) + 1 + 搬(n - 1, 借, 到, 从)

开始 = time.time()
次数 = 搬(20, "A", "C", "B")
用时 = time.time() - 开始
print("搬了", 次数, "次，用了", round(用时, 2), "秒")
print("一秒能搬", round(次数 / 用时), "次")

每秒 = round(次数 / 用时)            # 你的电脑一秒能搬几次（每台电脑不一样）

步 = 2 ** 64 - 1
print(步, "步")

一年 = 60 * 60 * 24 * 365           # 一年有多少秒
print("一秒搬一个：", 步 // 一年 // 100000000, "亿年")
print("派派的电脑：", 步 // 每秒 // 一年, "年")
