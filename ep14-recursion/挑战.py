#
# 搬家记录.txt 里有好几份汉诺塔的搬家记录，每份之间空一行。
# 每份第一行是层数 n；后面每行是一步，比如「A C」= 把 A 柱最上面的盘子搬到 C 柱。
# 一开始所有盘子都在 A 柱，从下到上是 n, n-1, …, 1（数字越大盘子越大）。
#
# 一份一份检查，每份打印一行，格式要一模一样：
#   全部搬到了 C 柱：        第 1 份：搬完了，用了 7 步，最少要 7 步
#   某一步从空柱子上拿：      第 5 份：第 8 步出错，B 塔是空的
#   某一步大盘子压小盘子：    第 2 份：第 5 步出错，大盘子 4 不能压在小盘子 3 上
#   某一步看不懂（不是两段、或者柱子不是 A/B/C）：第 4 份：第 2 步看不懂：A D
#   每一步都没错，但没搬完：  第 3 份：还没搬完，C 塔上只有 1 个盘子
# 一份记录在某一步出错了，就停在那一步，这一份后面的步骤不用再看。
#
# 要求：
#   1. 「最少要几步」用递归函数算（函数里调用它自己），不许用 **
#   2. 出错的时候 raise 一个你自己写的异常类（继承 Exception），在外面用 try/except 接住
#   3. 输出要和 期望输出.txt 一模一样。写完运行 python 检查挑战.py 自己验（有两关）
#
